import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';

class ThemeCubit extends Cubit<ThemeMode> {
  ThemeCubit() : super(ThemeMode.system);

  void toggleTheme() {
    if (state == ThemeMode.dark) {
      emit(ThemeMode.light);
    } else {
      emit(ThemeMode.dark);
    }
  }

  void setTheme(ThemeMode mode) => emit(mode);
}

class AppTheme {
  // Light Theme Palette
  static const Color primaryLight = Color(0xFF006A67);
  static const Color onPrimaryLight = Colors.white;
  static const Color secondaryLight = Color(0xFF006874);
  static const Color backgroundLight = Color(0xFFF8F9FA);
  static const Color surfaceLight = Colors.white;
  static const Color cardLight = Colors.white;
  static const Color errorLight = Color(0xFFBA1A1A);

  // Dark Theme Palette
  static const Color primaryDark = Color(0xFF51DBCD);
  static const Color onPrimaryDark = Color(0xFF003735);
  static const Color secondaryDark = Color(0xFF4FD8EB);
  static const Color backgroundDark = Color(0xFF121414);
